package io.jclaw.adapter.out.persistence.sql;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.TreeMap;
import javax.sql.DataSource;

/**
 * The SQL schema and its migrations.
 *
 * <p>Versioned DDL applied in order and recorded in {@code jclaw_schema}, so a database created
 * by an older build is brought forward on start and a newer database is refused rather than
 * misread. Each migration runs in one transaction. The DDL is written in the dialect H2 and
 * PostgreSQL share: identity columns, {@code TEXT}, plain indexes; nothing vendor-specific, so
 * one migration list serves the embedded and the hosted database.
 *
 * <p>The stores replay their rows in order and decode them themselves, exactly as they do from a
 * JSONL file, so what SQL adds is durability under concurrent writers, transactional rewrites,
 * indexed reads by run and thread, and a database an operator can back up and query — not a
 * second data model to keep in step with the first.
 *
 * <p>Version 1 put every store's rows in one table. Version 2 gives the busy ones a table each:
 * a store that grows without bound or is read on a hot path no longer shares a primary key
 * sequence, an index, or a page with every other store, and {@code SELECT * FROM jclaw_events}
 * is a thing an operator can type. The small configuration stores — MCP servers, extensions,
 * secrets, sessions — keep sharing {@code jclaw_rows}, because a table per concept is worth the
 * DDL only where the volume or the query pattern earns it, and a dozen near-empty tables would
 * make the schema harder to read for no gain. Per-tenant vaults land there too, since their
 * names are not known when the migration is written.
 */
public final class SqlSchema {

    private static final Logger log = LoggerFactory.getLogger(SqlSchema.class);

    /** One schema version: the statements that take the database from the previous one to it. */
    public record Migration(int version, String description, List<String> statements) {
    }

    /**
     * Stores with a table of their own, by store name.
     *
     * <p>These are the ones that grow with use or are read while a turn is running. Everything
     * else shares {@code jclaw_rows}; see the class note for why that line is where it is.
     */
    public static final Map<String, String> DEDICATED_TABLES = Map.of(
            "events", "jclaw_events",
            "transcript", "jclaw_transcript",
            "runs", "jclaw_runs",
            "checkpoints", "jclaw_checkpoints",
            "results", "jclaw_results",
            "approvals", "jclaw_approvals",
            "memory", "jclaw_memory",
            "routines", "jclaw_routines");

    /** The table a store's rows live in. */
    public static String tableFor(String store) {
        return DEDICATED_TABLES.getOrDefault(Objects.requireNonNull(store, "store"), "jclaw_rows");
    }

    /** Whether a store shares {@code jclaw_rows} and so must filter by store name. */
    public static boolean isShared(String store) {
        return !DEDICATED_TABLES.containsKey(store);
    }

    private static List<String> dedicate(String store, String table) {
        return List.of(
                "CREATE TABLE " + table + " ("
                        + " seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + " run VARCHAR(200),"
                        + " thread VARCHAR(200),"
                        + " body TEXT NOT NULL)",
                "CREATE INDEX " + table + "_run ON " + table + " (run)",
                "CREATE INDEX " + table + "_thread ON " + table + " (thread)",
                // Ordered by seq so append order survives the move; the identity column on the
                // new table reassigns it in the same order.
                "INSERT INTO " + table + " (run, thread, body)"
                        + " SELECT run, thread, body FROM jclaw_rows WHERE store = '" + store + "' ORDER BY seq",
                "DELETE FROM jclaw_rows WHERE store = '" + store + "'");
    }

    private static List<String> splitOutBusyStores() {
        List<String> statements = new ArrayList<>();
        // Sorted so the DDL is applied in a stable order, which makes a failed migration's
        // partial state reproducible rather than dependent on map iteration.
        new TreeMap<>(DEDICATED_TABLES).forEach((store, table) ->
                statements.addAll(dedicate(store, table)));
        return List.copyOf(statements);
    }

    /** The migrations, in order. Append; never edit a shipped one. */
    public static final List<Migration> MIGRATIONS = List.of(
            new Migration(1, "rows table", List.of(
                    "CREATE TABLE jclaw_rows ("
                            + " seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " store VARCHAR(64) NOT NULL,"
                            + " run VARCHAR(200),"
                            + " thread VARCHAR(200),"
                            + " body TEXT NOT NULL)",
                    "CREATE INDEX jclaw_rows_store ON jclaw_rows (store, seq)",
                    "CREATE INDEX jclaw_rows_run ON jclaw_rows (store, run)",
                    "CREATE INDEX jclaw_rows_thread ON jclaw_rows (store, thread)")),
            new Migration(2, "a table per busy store", splitOutBusyStores()),
            new Migration(3, "materialised run projections", List.of(
                    "CREATE TABLE jclaw_run_projection ("
                            + " run VARCHAR(200) PRIMARY KEY,"
                            + " thread VARCHAR(200),"
                            + " status VARCHAR(32) NOT NULL,"
                            + " updated_at TIMESTAMP NOT NULL,"
                            + " body TEXT NOT NULL)",
                    "CREATE INDEX jclaw_run_projection_thread ON jclaw_run_projection (thread)",
                    "CREATE INDEX jclaw_run_projection_status ON jclaw_run_projection (status)")),
            new Migration(4, "thread locks", List.of(
                    "CREATE TABLE jclaw_thread_locks ("
                            + " scope VARCHAR(400) PRIMARY KEY,"
                            + " owner VARCHAR(200) NOT NULL,"
                            + " acquired_at TIMESTAMP NOT NULL,"
                            + " expires_at TIMESTAMP NOT NULL)",
                    "CREATE INDEX jclaw_thread_locks_expiry ON jclaw_thread_locks (expires_at)")));

    private SqlSchema() {
    }

    /** The schema version this build expects. */
    public static int currentVersion() {
        return MIGRATIONS.get(MIGRATIONS.size() - 1).version();
    }

    /**
     * Brings the database to the current version, creating the version table on first use.
     *
     * @return the version the database was at before, 0 for a fresh database
     * @throws IllegalStateException when the database is newer than this build
     */
    public static int migrate(DataSource dataSource) {
        Objects.requireNonNull(dataSource, "dataSource");
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        TransactionTemplate tx = new TransactionTemplate(new DataSourceTransactionManager(dataSource));

        jdbc.execute("CREATE TABLE IF NOT EXISTS jclaw_schema ("
                + " version INT PRIMARY KEY,"
                + " description VARCHAR(200) NOT NULL,"
                + " applied_at TIMESTAMP NOT NULL)");
        Integer at = jdbc.queryForObject("SELECT COALESCE(MAX(version), 0) FROM jclaw_schema", Integer.class);
        int before = at == null ? 0 : at;
        if (before > currentVersion()) {
            throw new IllegalStateException("database schema is version " + before
                    + " but this build knows up to " + currentVersion() + "; upgrade jclaw");
        }
        for (Migration migration : MIGRATIONS) {
            if (migration.version() <= before) {
                continue;
            }
            tx.executeWithoutResult(status -> {
                for (String statement : migration.statements()) {
                    jdbc.execute(statement);
                }
                jdbc.update("INSERT INTO jclaw_schema (version, description, applied_at) VALUES (?, ?, ?)",
                        migration.version(), migration.description(), Timestamp.from(Instant.now()));
            });
            log.debug("storage: applied schema migration {} ({})", migration.version(), migration.description());
        }
        return before;
    }
}
